import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';
import { Player, PlayerStandingsRow, Round, Tournament } from '../types/chess';
import { calculateStandings } from './tiebreaks';

// Helper to format player label
function getPlayerDisplay(player?: Player | null): { name: string; rtg: string; title: string; fed: string } {
  if (!player) {
    return { name: 'BYE / Unassigned', rtg: '', title: '', fed: '' };
  }
  return {
    name: player.name,
    rtg: String(player.rating || '-'),
    title: player.title && player.title !== 'None' ? player.title : '',
    fed: player.federation || '',
  };
}

/**
 * Generate and download FIDE-compliant Pairings PDF for a specific round
 */
export function downloadPairingPDF(tournament: Tournament, roundNumber: number): void {
  const round = tournament.rounds.find((r) => r.roundNumber === roundNumber);
  if (!round) {
    alert(`Round ${roundNumber} pairings have not been generated yet.`);
    return;
  }

  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: 'a4',
  });

  const playerMap = new Map<string, Player>();
  tournament.players.forEach((p) => playerMap.set(p.id, p));

  // 1. Header Banner
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(15);
  doc.setTextColor(15, 23, 42); // slate-900
  doc.text(tournament.name.toUpperCase(), 14, 15);

  doc.setFontSize(11);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(180, 83, 9); // amber-700
  doc.text(`OFFICIAL PAIRINGS & RESULTS - ROUND ${roundNumber}`, 14, 22);

  // Metadata block
  doc.setFontSize(8.5);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(71, 85, 105); // slate-600

  const metaLeft = [
    `Venue: ${tournament.venue || 'Tournament Hall'}, ${tournament.city || ''} (${tournament.federation || 'FIDE'})`,
    `System: ${tournament.type.toUpperCase()} | Time Control: ${tournament.timeControlDescription}`,
  ];
  const metaRight = [
    `Chief Arbiter: ${tournament.chiefArbiter}`,
    `Default Time: ${tournament.defaultTimeMinutes === 0 ? 'Zero Tolerance' : `${tournament.defaultTimeMinutes} Minutes`}`,
  ];

  doc.text(metaLeft, 14, 28);
  doc.text(metaRight, 120, 28);

  // 2. Table Data
  const tableRows = round.pairings.map((p) => {
    const white = playerMap.get(p.whitePlayerId);
    const black = p.blackPlayerId ? playerMap.get(p.blackPlayerId) : null;

    const wDisp = getPlayerDisplay(white);
    const bDisp = getPlayerDisplay(black);

    const whiteText = `${wDisp.title ? `${wDisp.title} ` : ''}${wDisp.name} (${wDisp.rtg}) [${wDisp.fed}]`;
    const blackText = p.isBye
      ? `BYE (${p.byeType === 'half' ? '0.5 pt' : '1.0 pt'})`
      : `${bDisp.title ? `${bDisp.title} ` : ''}${bDisp.name} (${bDisp.rtg}) [${bDisp.fed}]`;

    const resultText = p.result === '*' ? '   -   ' : p.result;
    const noteText = p.anomalyReason || p.arbiterNote || (p.isBye ? 'Bye' : '');

    return [
      p.boardNumber ? `Board ${p.boardNumber}` : 'BYE',
      whiteText,
      resultText,
      blackText,
      noteText,
    ];
  });

  autoTable(doc, {
    startY: 37,
    head: [['Brd', 'White (Rating) [Fed]', 'Result', 'Black (Rating) [Fed]', 'Arbiter Note']],
    body: tableRows,
    theme: 'grid',
    styles: {
      fontSize: 8,
      cellPadding: 2.2,
      font: 'helvetica',
      textColor: [30, 41, 59],
      lineColor: [203, 213, 225],
      lineWidth: 0.15,
    },
    headStyles: {
      fillColor: [15, 23, 42], // slate-900
      textColor: [248, 250, 252],
      fontStyle: 'bold',
      halign: 'left',
    },
    columnStyles: {
      0: { cellWidth: 16, halign: 'center', fontStyle: 'bold' },
      1: { cellWidth: 68 },
      2: { cellWidth: 20, halign: 'center', fontStyle: 'bold' },
      3: { cellWidth: 68 },
      4: { cellWidth: 'auto', fontSize: 7, textColor: [100, 116, 139] },
    },
    alternateRowStyles: {
      fillColor: [248, 250, 252],
    },
  });

  // Footer & Signature Block
  const finalY = (doc as any).lastAutoTable?.finalY || 180;
  doc.setFontSize(8);
  doc.setFont('helvetica', 'italic');
  doc.setTextColor(100, 116, 139);
  doc.text(
    `Official noticeboard document generated by AgudPro Tournament Management System on ${new Date().toLocaleDateString()} at ${new Date().toLocaleTimeString()}.`,
    14,
    finalY + 8
  );

  doc.setFont('helvetica', 'normal');
  doc.setTextColor(30, 41, 59);
  doc.text('Chief Arbiter Signature: _______________________________', 120, finalY + 16);

  // Download
  const filename = `${tournament.name.replace(/\s+/g, '_')}_Pairing_R${roundNumber}.pdf`;
  doc.save(filename);
}

/**
 * Generate and download FIDE-compliant Standings PDF
 */
export function downloadStandingsPDF(
  tournament: Tournament,
  standings: PlayerStandingsRow[],
  afterRound?: number
): void {
  const doc = new jsPDF({
    orientation: 'landscape',
    unit: 'mm',
    format: 'a4',
  });

  // Header Banner
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(15);
  doc.setTextColor(15, 23, 42);
  doc.text(tournament.name.toUpperCase(), 14, 14);

  const roundSub = afterRound ? `AFTER ROUND ${afterRound}` : `FINAL STANDINGS`;
  doc.setFontSize(11);
  doc.setTextColor(180, 83, 9);
  doc.text(`OFFICIAL FIDE STANDINGS & TIE-BREAKS (${roundSub})`, 14, 21);

  // Metadata
  doc.setFontSize(8.5);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(71, 85, 105);

  const metaLeft = [
    `Venue: ${tournament.venue}, ${tournament.city} (${tournament.federation})`,
    `System: ${tournament.type.toUpperCase()} | Time Control: ${tournament.timeControlDescription}`,
  ];
  const metaRight = [
    `Chief Arbiter: ${tournament.chiefArbiter}`,
    `Tie-Break Order: Pts, Direct Encounter, Buchholz Cut-1, Buchholz, Sonneborn-Berger, Progressive, Wins`,
  ];

  doc.text(metaLeft, 14, 27);
  doc.text(metaRight, 140, 27);

  // Table rows
  const tableRows = standings.map((s) => {
    const title = s.player.title && s.player.title !== 'None' ? s.player.title : '';
    const cb = s.colorBalance > 0 ? `+${s.colorBalance}W` : s.colorBalance < 0 ? `${s.colorBalance}B` : '0';

    return [
      s.rank,
      s.player.seed,
      title,
      s.player.name,
      s.player.federation,
      s.player.rating,
      s.points.toFixed(1).replace('.0', ''),
      s.buchholzCut1.toFixed(1).replace('.0', ''),
      s.buchholz.toFixed(1).replace('.0', ''),
      s.sonnebornBerger.toFixed(2),
      s.directEncounter > 0 ? s.directEncounter.toFixed(1).replace('.0', '') : '-',
      s.progressiveScore.toFixed(1).replace('.0', ''),
      s.wins,
      cb,
      s.colorHistoryString || '-',
    ];
  });

  autoTable(doc, {
    startY: 35,
    head: [
      [
        'Rk',
        'SNo',
        'Title',
        'Player Name',
        'Fed',
        'Rating',
        'Pts',
        'BH-C1',
        'BH',
        'SB',
        'DE',
        'Prog',
        'W',
        'Col',
        'History',
      ],
    ],
    body: tableRows,
    theme: 'grid',
    styles: {
      fontSize: 8,
      cellPadding: 2,
      font: 'helvetica',
      textColor: [30, 41, 59],
      lineColor: [203, 213, 225],
      lineWidth: 0.15,
    },
    headStyles: {
      fillColor: [15, 23, 42],
      textColor: [248, 250, 252],
      fontStyle: 'bold',
      halign: 'center',
    },
    columnStyles: {
      0: { cellWidth: 10, halign: 'center', fontStyle: 'bold' },
      1: { cellWidth: 10, halign: 'center' },
      2: { cellWidth: 12, halign: 'center', fontStyle: 'bold', textColor: [180, 83, 9] },
      3: { cellWidth: 62, halign: 'left', fontStyle: 'bold' },
      4: { cellWidth: 12, halign: 'center' },
      5: { cellWidth: 16, halign: 'right' },
      6: { cellWidth: 14, halign: 'center', fontStyle: 'bold', fillColor: [241, 245, 249] },
      7: { cellWidth: 15, halign: 'right' },
      8: { cellWidth: 15, halign: 'right' },
      9: { cellWidth: 18, halign: 'right' },
      10: { cellWidth: 14, halign: 'right' },
      11: { cellWidth: 15, halign: 'right' },
      12: { cellWidth: 10, halign: 'center' },
      13: { cellWidth: 14, halign: 'center' },
      14: { cellWidth: 'auto', halign: 'left', fontSize: 7, textColor: [100, 116, 139] },
    },
    alternateRowStyles: {
      fillColor: [248, 250, 252],
    },
  });

  const finalY = (doc as any).lastAutoTable?.finalY || 160;
  doc.setFontSize(8);
  doc.setFont('helvetica', 'italic');
  doc.setTextColor(100, 116, 139);
  doc.text(
    `Official noticeboard document generated by AgudPro Tournament Management System on ${new Date().toLocaleDateString()} at ${new Date().toLocaleTimeString()}.`,
    14,
    finalY + 8
  );

  doc.setFont('helvetica', 'normal');
  doc.setTextColor(30, 41, 59);
  doc.text('Chief Arbiter Certification: _______________________________', 180, finalY + 14);

  const filename = `${tournament.name.replace(/\s+/g, '_')}_Standings${afterRound ? `_R${afterRound}` : ''}.pdf`;
  doc.save(filename);
}

/**
 * Download Standings strictly calculated up to a specific past round (R1, R2, etc.)
 */
export function downloadStandingsAfterRoundPDF(tournament: Tournament, roundNumber: number): void {
  const slicedRounds = tournament.rounds.slice(0, roundNumber);
  const standingsAfter = calculateStandings(tournament.players, slicedRounds);
  downloadStandingsPDF(tournament, standingsAfter, roundNumber);
}
